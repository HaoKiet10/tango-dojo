// One-time conversion: legacy/data.js (positional arrays) → typed src/data/*.ts.
// Kept for reference; it needs legacy/data.js, which is deleted once the rebuild ships.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const SRC = "legacy/data.js";
if (!existsSync(SRC)) {
  console.log(`${SRC} no longer exists; the data already lives in src/data/. Nothing to do.`);
  process.exit(0);
}
const ctx = {};
vm.runInNewContext(readFileSync(SRC, "utf8").replace(/^const /gm, "this."), ctx);

const kanji = ctx.KANJI.map(([char, hanViet, on, kun, meaning, level, word, reading, wm]) =>
  ({ char, hanViet, on, kun, meaning, level, example: { word, reading, meaning: wm } }));
const vocab = ctx.VOCAB.map(([word, reading, meaning, pos, level, ja, vi]) =>
  ({ word, reading, meaning, pos, level, sentence: { ja, vi } }));
const info = Object.fromEntries(Object.entries(ctx.KANJI_EXTRA).map(([c, [hanViet, meaning]]) => {
  const [on, kun] = ctx.KANJI_EXTRA_RD[c] ?? ["", ""];
  return [c, { hanViet, meaning, on, kun }];
}));

const header = "// Generated by scripts/convert-data.mjs from the audited legacy data.js. Edit freely from here on.\n";
const out = (file, type, name, value) => writeFileSync(file,
  `${header}import type { ${type} } from "./types";\n\nexport const ${name}: ${type === "KanjiInfo" ? "Record<string, KanjiInfo>" : type + "[]"} = ${JSON.stringify(value, null, 2)};\n`);
out("src/data/kanji.ts", "Kanji", "KANJI", kanji);
out("src/data/vocab.ts", "Vocab", "VOCAB", vocab);
out("src/data/kanjiInfo.ts", "KanjiInfo", "KANJI_INFO", info);
console.log(`kanji ${kanji.length}, vocab ${vocab.length}, kanji info ${Object.keys(info).length}`);
